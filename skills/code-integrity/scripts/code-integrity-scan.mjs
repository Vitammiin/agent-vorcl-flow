#!/usr/bin/env node

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_EXTENSIONS = new Set([
  '.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx', '.vue', '.svelte', '.html', '.htm',
  '.py', '.go', '.java', '.kt', '.kts', '.cs', '.php', '.rb', '.rs', '.razor', '.cshtml',
])

const HARD_EXCLUDED_DIRS = new Set([
  '.git', '.hg', '.svn', 'node_modules', 'vendor', 'vendors', 'dist', 'build', 'coverage',
  '.next', '.nuxt', '.svelte-kit', 'target', 'bin', 'obj', '.venv', 'venv', '__pycache__',
])

const TEST_SEGMENTS = new Set([
  'test', 'tests', '__tests__', 'spec', 'specs', 'fixtures', '__fixtures__', 'stories',
  'storybook', 'examples', 'example', 'samples', 'sample', 'seeds', 'seed', 'docs', 'migrations',
])

const GENERATED_MARKERS = ['generated', 'autogenerated', 'auto-generated', '.gen.', '.generated.']
const MOCK_IDENTIFIER = /\b(mock(?:ed|data|response|service|server|client|repository|repo)?|fake(?:r|data|response|service|user|users)?|dummy(?:data|response|user)?|stub(?:bed|data|response)?|sampleData|demoData|fixtureData)\b/i
const MOCK_FRAMEWORK = /(?:from\s+|require\s*\(|import\s+.*?from\s+|using\s+|use\s+)["'](?:msw|@faker-js\/faker|faker|casual|nock|sinon|responses|requests_mock|unittest\.mock|wiremock|mockito|mockk|mockwebserver|moq|nsubstitute|bogus|mockery|webmock|vcr|mockall|httpmock|gofakeit)(?:[\/'".]|\b)/i
const MOCK_REGISTRATION = /\b(?:setupWorker|setupServer|jest\.mock|vi\.mock|sinon\.stub|Mockito\.mock|WireMockServer|MockWebServer|NSubstitute|WebMock\.stub_request|httpmock::MockServer)\b/
const PLACEHOLDER = /\b(?:lorem ipsum|placeholder\.com|placehold\.co|example\.(?:com|org|net)|test@test\.[a-z]{2,}|john\.doe@|jane\.doe@)\b/i
const ENDPOINT = /(?:https?:\/\/(?:localhost|127\.0\.0\.1|0\.0\.0\.0|\[::1\])(?::\d+)?|\/(?:Users|home)\/[A-Za-z0-9._-]+\/)/i
const PROD_FIXTURE_IMPORT = /(?:from\s+|require\s*\(|import\s+.*?from\s+)["'][^"']*(?:fixtures?|__mocks__|mocks?|stories|seeds?|demo-data|sample-data)[^"']*["']/i
const STATIC_API_RESPONSE = /\b(?:res\.json|response\.json|reply\.send|jsonify|ResponseEntity\.ok|Results\.Ok|Ok\s*\(|render\s+json:|JsonResponse)\s*\(?(?:\s*\[\s*\{|\s*\{[^}\n]{0,100}(?:name|email|title|id)\s*[:=])/i
const TRANSLATION_CALL = /\b(?:t|translate|gettext|_|i18n\.t|intl\.formatMessage|localizer\[[^\]]+\])\s*\(/
const USER_FIELD_LITERAL = /\b(?:message|detail|description|subject|title|label|placeholder|tooltip|caption|error_description)\b\s*(?::|=>|=)\s*[rubf@]*["'`]([^"'`]{3,})["'`]/i
const JSX_TEXT = />\s*([A-Za-zÀ-žА-Яа-яЁё][^<>{}\n]{2,})\s*</
const TEMPLATE_TEXT = />([^<>{}\n]*[A-Za-zÀ-žА-Яа-яЁё][^<>{}\n]{2,})</
const DATABASE_OWNED_NAME = /(?:plan|tier|price|fee|commission|tax|discount|quota|limit|role|category|product|catalog|tenant|organization|account|currency|entitlement|subscription)/i
const CONSTANT_DECLARATION = /\b(?:const|static\s+final|readonly|final|let|var)\b[^=\n]{0,100}=\s*(?:["'`][^"'`]+["'`]|-?\d+(?:\.\d+)?|\[|\{|array\s*\()/i
const UPPERCASE_ASSIGNMENT = /^\s*[A-Z][A-Z0-9_]{2,}\s*=\s*(?:[rubf@]*["'`][^"'`]+["'`]|-?\d+(?:\.\d+)?|\[|\{|\()/
const DEFAULT_OR_NAMED_PARAMETER = /(?:^\s*|[({,]\s*)\b(?:plan|tier|price|fee|commission|tax|discount|quota|limit|role|category|product|tenant|account|currency|entitlement|subscription)\w*\s*(?::\s*[A-Za-z0-9_?.<>\[\]]+\s*)?(?:=|:)\s*(?:[rubf@]*["'`][^"'`]+["'`]|-?\d+(?:\.\d+)?)/i
const STATIC_DOMAIN_COLLECTION = /\b(?:plans?|tiers?|prices?|fees?|discounts?|roles?|categories?|products?|catalog|currencies|entitlements?|subscriptions?)\w*\b[^=\n]{0,80}=\s*(?:\[\s*\{|\{|array\s*\()/i

const severityRank = { low: 1, medium: 2, high: 3, critical: 4 }

function normalize(relativePath) {
  return relativePath.split(path.sep).join('/')
}

function languageFor(file) {
  const ext = path.extname(file).toLowerCase()
  if (['.js', '.jsx', '.mjs', '.cjs', '.ts', '.tsx'].includes(ext)) return 'typescript/javascript'
  if (['.vue', '.svelte', '.html', '.htm'].includes(ext)) return 'web-template'
  if (ext === '.py') return 'python'
  if (ext === '.go') return 'go'
  if (['.java', '.kt', '.kts'].includes(ext)) return 'java/kotlin'
  if (['.cs', '.razor', '.cshtml'].includes(ext)) return 'csharp'
  if (ext === '.php') return 'php'
  if (ext === '.rb') return 'ruby'
  if (ext === '.rs') return 'rust'
  return 'unknown'
}

function isTestLike(relativePath) {
  const normalized = normalize(relativePath).toLowerCase()
  const segments = normalized.split('/')
  const base = segments.at(-1)
  return segments.some((segment) => TEST_SEGMENTS.has(segment)) ||
    /(?:^|\.)(?:test|spec|stories|story)\.[^.]+$/.test(base) ||
    /(?:snapshot|fixture|mock)\.[^.]+$/.test(base)
}

function isGenerated(relativePath, content) {
  const lower = normalize(relativePath).toLowerCase()
  return GENERATED_MARKERS.some((marker) => lower.includes(marker)) ||
    /(?:code generated .* do not edit|auto-generated file|@generated)/i.test(content.slice(0, 500))
}

function scopeFor(relativePath) {
  const normalized = `/${normalize(relativePath).toLowerCase()}/`
  if (/\/(?:frontend|client|web|ui|pages|components|views|app)\//.test(normalized)) return 'Frontend'
  if (/\/(?:mobile|ios|android)\//.test(normalized)) return 'Mobile'
  if (/\/(?:backend|server|api|controllers?|routes?|handlers?|services?|repositories?)\//.test(normalized)) return 'Backend'
  return 'Shared'
}

function looksLikeComment(line, language) {
  const value = line.trim()
  if (!value) return true
  if (language === 'python' || language === 'ruby') return value.startsWith('#')
  return value.startsWith('//') || value.startsWith('/*') || value.startsWith('*') || value.startsWith('<!--')
}

function compactEvidence(line) {
  return line.trim().replace(/\s+/g, ' ').slice(0, 240)
}

function addFinding(findings, seen, base, rule) {
  const key = `${base.file}:${base.line}:${rule.id}`
  if (seen.has(key)) return
  seen.add(key)
  findings.push({ ...base, ...rule })
}

function hardcodeRules(line, context) {
  const rules = []
  if (PLACEHOLDER.test(line)) {
    rules.push({ id: 'hardcode.placeholder-content', severity: 'high', confidence: 'high', category: 'hardcode', message: 'Placeholder/example content appears in production source.' })
  }
  if (ENDPOINT.test(line) && !/\b(?:test|dev|development|example)\b/i.test(context.relativePath)) {
    rules.push({ id: 'hardcode.environment-value', severity: 'medium', confidence: 'high', category: 'hardcode', message: 'Environment-specific endpoint or developer path is embedded in source.' })
  }
  if (USER_FIELD_LITERAL.test(line) && !TRANSLATION_CALL.test(line)) {
    rules.push({ id: 'hardcode.user-visible-field', severity: context.hasI18n ? 'high' : 'medium', confidence: 'medium', category: 'hardcode', message: 'A user-facing field contains a literal outside an evident localization/config boundary.' })
  }
  const ext = path.extname(context.relativePath).toLowerCase()
  const renderedText = ['.jsx', '.tsx'].includes(ext) ? JSX_TEXT.test(line) :
    ['.vue', '.svelte', '.html', '.htm', '.razor', '.cshtml'].includes(ext) ? TEMPLATE_TEXT.test(line) : false
  if (renderedText && !TRANSLATION_CALL.test(line) && !/[=:]["'][^"']+["']/.test(line.trim())) {
    rules.push({ id: 'hardcode.rendered-text', severity: context.hasI18n ? 'high' : 'medium', confidence: 'medium', category: 'hardcode', message: 'Rendered text literal bypasses an evident content/localization boundary.' })
  }
  if (context.scope === 'Backend' && DATABASE_OWNED_NAME.test(line)) {
    const staticCollection = STATIC_DOMAIN_COLLECTION.test(line)
    if (staticCollection) {
      rules.push({ id: 'hardcode.database-owned-collection', severity: 'high', confidence: 'low', category: 'hardcode', message: 'A backend business catalog/collection is embedded in source; compare it with database-owned records.' })
    } else if (CONSTANT_DECLARATION.test(line) || UPPERCASE_ASSIGNMENT.test(line)) {
      rules.push({ id: 'hardcode.database-owned-constant', severity: 'medium', confidence: 'low', category: 'hardcode', message: 'A backend business value is stored in a constant; verify whether the database is the system of record.' })
    }
    if (DEFAULT_OR_NAMED_PARAMETER.test(line) && !UPPERCASE_ASSIGNMENT.test(line)) {
      rules.push({ id: 'hardcode.database-owned-parameter', severity: 'medium', confidence: 'low', category: 'hardcode', message: 'A backend default or named parameter embeds a business value; trace whether it bypasses database state.' })
    }
  }
  return rules
}

function mockRules(line) {
  const rules = []
  if (MOCK_FRAMEWORK.test(line)) rules.push({ id: 'mocks.framework-import', severity: 'high', confidence: 'high', category: 'mocks', message: 'Mock/fake framework is imported by production source.' })
  if (MOCK_REGISTRATION.test(line)) rules.push({ id: 'mocks.runtime-registration', severity: 'high', confidence: 'high', category: 'mocks', message: 'Mock interception/runtime is registered in production source.' })
  if (PROD_FIXTURE_IMPORT.test(line)) rules.push({ id: 'mocks.fixture-import', severity: 'high', confidence: 'high', category: 'mocks', message: 'Production source imports a fixture/mock/story/seed/demo module.' })
  if (STATIC_API_RESPONSE.test(line)) rules.push({ id: 'mocks.static-api-response', severity: 'high', confidence: 'medium', category: 'mocks', message: 'An API response appears to return a static sample record or collection.' })
  if (MOCK_IDENTIFIER.test(line) && /(?:const|let|var|def|class|func|fun|private|public|static|:=|=)/.test(line)) {
    rules.push({ id: 'mocks.suspicious-identifier', severity: 'medium', confidence: 'low', category: 'mocks', message: 'Mock/fake/demo identifier exists in production source; trace consumers before confirming.' })
  }
  if (PLACEHOLDER.test(line)) rules.push({ id: 'mocks.placeholder-data', severity: 'high', confidence: 'high', category: 'mocks', message: 'Placeholder/example record appears in production source.' })
  return rules
}

function walk(root, current = root, files = []) {
  for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
    if (entry.isSymbolicLink()) continue
    if (entry.isDirectory() && HARD_EXCLUDED_DIRS.has(entry.name.toLowerCase())) continue
    const absolute = path.join(current, entry.name)
    if (entry.isDirectory()) walk(root, absolute, files)
    else if (entry.isFile() && SOURCE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) files.push(absolute)
  }
  return files
}

function detectI18n(root) {
  const manifests = ['package.json', 'pyproject.toml', 'requirements.txt', 'go.mod', 'pom.xml', 'build.gradle', 'build.gradle.kts', 'Gemfile', 'composer.json', 'Cargo.toml']
  const signal = /next-intl|react-i18next|i18next|formatjs|vue-i18n|svelte-i18n|gettext|babel|django.*i18n|flask-babel|go-i18n|spring.*messages|resourcebundle|resx|rails-i18n|symfony\/translation|fluent/i
  return manifests.some((manifest) => {
    const file = path.join(root, manifest)
    return fs.existsSync(file) && signal.test(fs.readFileSync(file, 'utf8'))
  }) || ['locales', 'locale', 'i18n', 'translations'].some((name) => fs.existsSync(path.join(root, name)))
}

export function auditPath(targetPath, options = {}) {
  const root = path.resolve(targetPath)
  const mode = options.mode || 'all'
  if (!['all', 'hardcode', 'mocks'].includes(mode)) throw new Error(`Unsupported mode: ${mode}`)
  if (!fs.existsSync(root)) throw new Error(`Path does not exist: ${root}`)
  const stat = fs.statSync(root)
  const files = stat.isDirectory() ? walk(root) : [root]
  const baseRoot = stat.isDirectory() ? root : path.dirname(root)
  const hasI18n = detectI18n(baseRoot)
  const findings = []
  const seen = new Set()
  const languages = new Set()
  let suppressedTestFiles = 0
  let generatedFiles = 0

  for (const absolute of files.sort()) {
    const relativePath = normalize(path.relative(baseRoot, absolute) || path.basename(absolute))
    const content = fs.readFileSync(absolute, 'utf8')
    const language = languageFor(absolute)
    languages.add(language)
    const testLike = isTestLike(relativePath)
    if (testLike && !options.includeTest) {
      suppressedTestFiles++
      continue
    }
    if (isGenerated(relativePath, content)) {
      generatedFiles++
      continue
    }
    const disposition = testLike ? 'legitimate-test' : 'production-candidate'
    const lines = content.split(/\r?\n/)
    lines.forEach((line, index) => {
      if (looksLikeComment(line, language)) return
      const base = { file: relativePath, line: index + 1, scope: scopeFor(relativePath), language, disposition, evidence: compactEvidence(line) }
      if (mode !== 'mocks') for (const rule of hardcodeRules(line, { relativePath, hasI18n, scope: base.scope })) addFinding(findings, seen, base, rule)
      if (mode !== 'hardcode') for (const rule of mockRules(line)) addFinding(findings, seen, base, rule)
    })
  }

  findings.sort((a, b) => severityRank[b.severity] - severityRank[a.severity] || a.file.localeCompare(b.file) || a.line - b.line)
  return {
    version: 1,
    root,
    mode,
    readOnly: true,
    hasI18n,
    languages: [...languages].sort(),
    summary: { scannedSourceFiles: files.length - suppressedTestFiles - generatedFiles, findings: findings.length, suppressedTestFiles, generatedFiles },
    findings,
    limitations: ['Lexical candidates require source-context and production-reachability review.', 'Dynamic imports, generated build graphs, and runtime dependency-injection bindings are not fully resolved.'],
  }
}

function parseArgs(argv) {
  const options = { target: '.', mode: 'all', format: 'text', includeTest: false, failOn: null }
  for (let index = 0; index < argv.length; index++) {
    const arg = argv[index]
    if (arg === '--mode') options.mode = argv[++index]
    else if (arg === '--format') options.format = argv[++index]
    else if (arg === '--include-test') options.includeTest = true
    else if (arg === '--fail-on') options.failOn = argv[++index]
    else if (arg === '--help' || arg === '-h') options.help = true
    else if (arg.startsWith('-')) throw new Error(`Unknown option: ${arg}`)
    else options.target = arg
  }
  return options
}

function printText(report) {
  const output = []
  output.push(`Code Integrity (${report.mode}) — ${report.root}`)
  output.push(`Files: ${report.summary.scannedSourceFiles}; findings: ${report.summary.findings}; tests suppressed: ${report.summary.suppressedTestFiles}; generated suppressed: ${report.summary.generatedFiles}`)
  output.push(`Languages: ${report.languages.join(', ') || 'none'}; i18n detected: ${report.hasI18n ? 'yes' : 'no'}`)
  for (const finding of report.findings) {
    output.push(`${finding.severity.toUpperCase()} ${finding.scope} ${finding.file}:${finding.line} [${finding.id}] (${finding.confidence})`)
    output.push(`  ${finding.message}`)
    output.push(`  ${finding.evidence}`)
  }
  output.push('Limitations: lexical candidates require contextual reachability review; no target code was executed.')
  return output.join('\n')
}

const invoked = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invoked) {
  try {
    const options = parseArgs(process.argv.slice(2))
    if (options.help) {
      console.log('Usage: code-integrity-scan.mjs [path] [--mode all|hardcode|mocks] [--format text|json] [--include-test] [--fail-on low|medium|high|critical]')
      process.exit(0)
    }
    if (!['text', 'json'].includes(options.format)) throw new Error(`Unsupported format: ${options.format}`)
    if (options.failOn && !severityRank[options.failOn]) throw new Error(`Unsupported severity: ${options.failOn}`)
    const report = auditPath(options.target, options)
    console.log(options.format === 'json' ? JSON.stringify(report, null, 2) : printText(report))
    if (options.failOn && report.findings.some((finding) => severityRank[finding.severity] >= severityRank[options.failOn])) process.exitCode = 2
  } catch (error) {
    console.error(`code-integrity: ${error.message}`)
    process.exitCode = 1
  }
}
