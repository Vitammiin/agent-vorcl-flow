#!/usr/bin/env node
// Canonical prompts live in agents/, commands/, skills/. Codex is an adapter,
// never a second editable source of workflow policy.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const write = process.argv.includes('--write')
const registry = JSON.parse(fs.readFileSync(path.join(root, 'scripts/roles.json'), 'utf8'))
const roles = new Set(registry.roles.map(({ id }) => id))
const marker = '<!-- generated by scripts/generate-codex-skills.mjs; edit canonical agents/, commands/ or skills/ -->'
const outputs = new Map()
const commandRoutes = new Map()
for (const entry of fs.readdirSync(path.join(root, 'commands'), { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith('.md')) {
    const name = entry.name.slice(0, -3)
    commandRoutes.set(`/${name}`, `$${name}`)
  } else if (entry.isDirectory()) {
    for (const file of fs.readdirSync(path.join(root, 'commands', entry.name))) {
      if (file.endsWith('.md')) commandRoutes.set(`/${entry.name}:${file.slice(0, -3)}`, `$${entry.name}-${file.slice(0, -3)}`)
    }
  }
}

function parse(source) {
  const match = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/)
  if (!match) throw new Error('Missing frontmatter')
  const description = match[1].match(/^description:\s*(.*)$/m)?.[1]
  if (!description) throw new Error('Missing description')
  return { frontmatter: match[1], body: match[2].trim(), description }
}
function adapt(body) {
  return body
    .replace(/\$ARGUMENTS/g, 'запрос пользователя')
    .replace(/(?<![\w/])\/[a-z][a-z-]*(?::[a-z][a-z-]*)?(?![\w/-])/g, (route) => commandRoutes.get(route) ?? route)
    .replace(/`([a-z][a-z-]*)`/g, (match, name) => roles.has(name) ? `\`$${name}\`` : match)
}
function render(name, source, extra = '') {
  const { description, body } = parse(source)
  return `---\nname: ${name}\ndescription: ${JSON.stringify(description.startsWith('"') ? JSON.parse(description) : description)}\n---\n\n${marker}\n\n${adapt(body)}${extra ? `\n\n${extra}` : ''}\n`
}
function read(rel) { return fs.readFileSync(path.join(root, rel), 'utf8') }

// Domain skills keep byte-for-byte parity, including multiline frontmatter.
for (const entry of fs.readdirSync(path.join(root, 'skills'), { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const file = `skills/${entry.name}/SKILL.md`
  if (fs.existsSync(path.join(root, file))) outputs.set(entry.name, read(file))
}
for (const role of roles) {
  const domain = outputs.get(role)
  const extra = domain && !domain.includes('generated by scripts/generate-role-skills.mjs')
    ? `<!-- canonical domain skill: skills/${role}/SKILL.md -->\n\n${parse(domain).body}` : ''
  outputs.set(role, render(role, read(`agents/${role}.md`), extra))
}
for (const entry of fs.readdirSync(path.join(root, 'commands'), { withFileTypes: true })) {
  if (entry.isFile() && entry.name.endsWith('.md')) {
    const name = entry.name.slice(0, -3)
    outputs.set(name, render(name, read(`commands/${entry.name}`)))
  } else if (entry.isDirectory()) {
    for (const file of fs.readdirSync(path.join(root, 'commands', entry.name))) {
      if (file.endsWith('.md')) outputs.set(`${entry.name}-${file.slice(0, -3)}`, render(`${entry.name}-${file.slice(0, -3)}`, read(`commands/${entry.name}/${file}`)))
    }
  }
}
const drift = []
for (const [name, expected] of outputs) {
  const target = path.join(root, 'codex/skills', name, 'SKILL.md')
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === expected) continue
  if (write) { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, expected) }
  else drift.push(path.relative(root, target))
}
if (drift.length) {
  process.stderr.write(`Codex prompt drift (run node scripts/generate-codex-skills.mjs --write):\n${drift.join('\n')}\n`)
  process.exitCode = 1
} else process.stdout.write(`Codex prompts ${write ? 'generated' : 'verified'}: ${outputs.size}\n`)
