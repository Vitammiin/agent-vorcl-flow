#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const registry = JSON.parse(fs.readFileSync(path.join(root, 'scripts/roles.json'), 'utf8'))
const marker = '<!-- generated by scripts/generate-role-skills.mjs; edit scripts/roles.json or agents/<role>.md -->'
const write = process.argv.includes('--write')
const errors = []

function render(role) {
  const description = `${role.route}. Primary owner: ${role.owns}. Do not use for: ${role.notFor}. Use when this role is selected by the Agent-Vorcl-Flow router.`
  return `---\nname: ${role.id}\ndescription: ${JSON.stringify(description)}\n---\n\n${marker}\n\n# Role: ${role.id}\n\nRead \`../../agents/${role.id}.md\` completely and follow it as the canonical persona. Load only the task/domain skills needed for the current request. Routing ownership and negative criteria come from \`../../scripts/roles.json\`.\n`
}

for (const role of registry.roles) {
  const directory = path.join(root, 'skills', role.id)
  const file = path.join(directory, 'SKILL.md')
  if (fs.existsSync(file)) {
    const current = fs.readFileSync(file, 'utf8')
    if (!current.includes(marker)) continue
    const expected = render(role)
    if (write && current !== expected) fs.writeFileSync(file, expected)
    else if (!write && current !== expected) errors.push(`generated role skill drift: skills/${role.id}/SKILL.md`)
    continue
  }
  if (write) {
    fs.mkdirSync(directory, { recursive: true })
    fs.writeFileSync(file, render(role))
  } else errors.push(`missing native role skill: skills/${role.id}/SKILL.md`)
}

if (errors.length) {
  errors.forEach((error) => process.stderr.write(`FAIL: ${error}\n`))
  process.exit(1)
}
process.stdout.write(`Role skills ${write ? 'generated' : 'verified'}: ${registry.roles.length} roles\n`)
